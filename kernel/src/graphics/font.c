const uint8_t *font_get_glyph(uint8_t c)
{
    return &s_font_8x16[(size_t)c * FONT_HEIGHT];
}

void font_draw_char(struct limine_framebuffer *framebuffer, int x, int y, char c, uint32_t fg, uint32_t bg)
{
    if (framebuffer == NULL || framebuffer->address == NULL)
    {
        return;
    }

    if (x < 0 || (uint64_t)(x + FONT_WIDTH) > framebuffer->width || y < 0 ||
        (uint64_t)(y + FONT_HEIGHT) > framebuffer->height)
    {
        return;
    }

    const uint8_t *glyph = font_get_glyph((uint8_t)c);
    uint32_t fg_pixel = framebuffer_format_color(framebuffer, fg);
    uint32_t bg_pixel = framebuffer_format_color(framebuffer, bg);

    if (framebuffer_is_backbuffer_enabled())
    {
        uint32_t *backbuffer = framebuffer_get_backbuffer();
        if (backbuffer != NULL)
        {
            for (int dy = 0; dy < FONT_HEIGHT; dy++)
            {
                uint8_t line = glyph[dy];
                uint32_t *row = &backbuffer[(size_t)(y + dy) * framebuffer->width + (size_t)x];
                for (int dx = 0; dx < FONT_WIDTH; dx++)
                {
                    row[dx] = (line & (0x80 >> dx)) ? fg_pixel : bg_pixel;
                }
            }
            framebuffer_mark_dirty(y, y + FONT_HEIGHT);
            return;
        }
    }

    // Direct VRAM fallback
    for (int dy = 0; dy < FONT_HEIGHT; dy++)
    {
        uint8_t line = glyph[dy];
        for (int dx = 0; dx < FONT_WIDTH; dx++)
        {
            uint32_t pixel = (line & (0x80 >> dx)) ? fg : bg;
            framebuffer_putPixel(framebuffer, (Vec2){x + dx, y + dy}, pixel);
        }
    }
}

void font_draw_string(struct limine_framebuffer *framebuffer, int x, int y, const char *str, uint32_t fg,
                      uint32_t bg)
{
    if (framebuffer == NULL || str == NULL)
    {
        return;
    }

    int curr_x = x;
    while (*str != 0)
    {
        if (*str == 10)
        {
            curr_x = x;
            y += FONT_HEIGHT;
        }
        else
        {
            font_draw_char(framebuffer, curr_x, y, *str, fg, bg);
            curr_x += FONT_WIDTH;
        }
        str++;
    }
}
